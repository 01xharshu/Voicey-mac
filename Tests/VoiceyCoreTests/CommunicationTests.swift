import Foundation
import VoiceyCore
func communicationChecks() throws {
 let chat=Conversation(id:"rahul-1",name:"Rahul"),other=Conversation(id:"rahul-2",name:"Rahul",isGroup:true)
 expectEqual(ContactResolver.resolve("Rahul",in:[chat]),.found(chat))
 expectEqual(ContactResolver.resolve("Rahul",in:[chat,other]),.ambiguous([chat,other]))
 expectEqual(ContactResolver.resolve("Rah",in:[chat]),.missing)
 let now=Date(timeIntervalSince1970:1_000_000),interval=DateInterval(start:now,end:now.addingTimeInterval(3600))
 let incoming=ChatMessage(id:"1",conversationID:chat.id,text:"Hello",date:now.addingTimeInterval(10),direction:.incoming,unread:true)
 let outgoing=ChatMessage(id:"2",conversationID:chat.id,text:"Hello",date:now.addingTimeInterval(20),direction:.outgoing,unread:false)
 let snapshot=ChatSnapshot(conversation:chat,messages:[incoming,incoming,outgoing],verifiedInterval:interval)
 expectEqual(MessageCounter.count(snapshot,scope:.interval(interval)).count,1)
 expectTrue(MessageCounter.count(snapshot,scope:.interval(interval)).exact)
 expectEqual(MessageCounter.count(snapshot,scope:.unread).count,1)
 expectFalse(MessageCounter.count(snapshot,scope:.unread).exact)
 expectFalse(MessageCounter.count(ChatSnapshot(conversation:chat,messages:[incoming]),scope:.interval(interval)).exact)
 let unknown=ChatMessage(conversationID:chat.id,text:nil,date:nil,direction:.unknown)
 expectEqual(MessageCounter.count(ChatSnapshot(conversation:chat,messages:[unknown]),scope:.visible).count,0)
 let noID=ChatMessage(conversationID:chat.id,text:"same",date:now,direction:.incoming)
 expectEqual(MessageCounter.count(ChatSnapshot(conversation:chat,messages:[noID,noID]),scope:.visible).count,2)
 expectFalse(MessageCounter.count(ChatSnapshot(conversation:chat,messages:[noID]),scope:.visible).exact)
 var calendar=Calendar(identifier:.gregorian);calendar.timeZone=TimeZone(secondsFromGMT:19800)!
 expectTrue(MessageCounter.today(now:now,calendar:calendar).contains(now))
 let exact=ReplyProposal(conversationID:chat.id,text:"Hello",mode:.exact)
 expectEqual(MessagingPolicy.evaluate(exact,verifiedConversation:chat.id,explicitSend:true),.execute)
 expectEqual(MessagingPolicy.evaluate(exact,verifiedConversation:other.id,explicitSend:true),.clarify("Verify the intended conversation first."))
 expectEqual(MessagingPolicy.evaluate(ReplyProposal(conversationID:chat.id,text:"Hello",mode:.draft),verifiedConversation:chat.id,explicitSend:false),.execute)
 expectEqual(MessagingPolicy.evaluate(ReplyProposal(conversationID:chat.id,text:"Hello",mode:.contextual),verifiedConversation:chat.id,explicitSend:true),.confirm("Hello"))
 expectEqual(MessagingPolicy.evaluate(ReplyProposal(conversationID:chat.id,text:"",mode:.exact),verifiedConversation:chat.id,explicitSend:true),.clarify("What should the message say?"))
 expectTrue(MessagingPolicy.verifiedSubmission(exact,in:snapshot,after:now))
 expectFalse(MessagingPolicy.verifiedSubmission(exact,in:snapshot,after:now.addingTimeInterval(100)))
 var watch=ReplyWatch(conversation:chat,created:now,expires:interval.end)
 let unrelated=ChatMessage(id:"3",conversationID:other.id,text:nil,date:now.addingTimeInterval(10),direction:.incoming)
 expectFalse(watch.observe(unrelated,now:now.addingTimeInterval(30)))
 expectFalse(watch.observe(outgoing,now:now.addingTimeInterval(30)))
 expectTrue(watch.observe(incoming,now:now.addingTimeInterval(30)))
 expectFalse(watch.observe(incoming,now:now.addingTimeInterval(30)))
 expectEqual(watch.status,.triggered)
 var timeout=ReplyWatch(conversation:chat,created:now,expires:interval.end)
 expectFalse(timeout.timeout(now:now));expectTrue(timeout.timeout(now:interval.end));expectFalse(timeout.timeout(now:interval.end))
 let directory=FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
 defer{try? FileManager.default.removeItem(at:directory)}
 let url=directory.appendingPathComponent("watches.json"),store=try CommunicationStore(url:url)
 try store.update([ReplyWatch(conversation:chat,created:now,expires:interval.end)])
 expectEqual(try CommunicationStore(url:url).watches.count,1)
 try store.cancelAll();expectEqual(store.watches[0].status,.cancelled)
 try store.clear();expectTrue(store.watches.isEmpty)
 let waiting=ReplyWatch(conversation:chat,created:now,expires:interval.end)
 let triggered=WatchProcessor.process([waiting],messages:[incoming],now:now.addingTimeInterval(30),connected:true)
 expectEqual(triggered.alerts.count,1);expectEqual(triggered.watches[0].status,.triggered)
 expectEqual(WatchProcessor.process(triggered.watches,messages:[incoming],now:now.addingTimeInterval(40),connected:true).alerts.count,0)
 let disconnected=WatchProcessor.process([waiting],messages:[incoming],now:now.addingTimeInterval(30),connected:false)
 expectEqual(disconnected.watches[0].status,.paused);expectTrue(disconnected.alerts.isEmpty)
 expectEqual(WatchProcessor.process(disconnected.watches,messages:[incoming],now:now.addingTimeInterval(40),connected:true).watches[0].status,.paused)
 expectEqual(WatchProcessor.process([waiting],messages:[],now:interval.end,connected:false).alerts[0].title,"Reply deadline reached")
 print("CHECK communication fixtures: resolution, counts, authorization, submission, persistence, matching, deduplication, cancellation, timeout")
}
